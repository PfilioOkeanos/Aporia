export function resourceDetails(group, item) {
    const number = Number(item.id.match(/-(\d+)\.png$/i)?.[1]);
    const source = (group === "elemente" ? elements : materials)[number - 1];
    if (!source) return {};
    if (group === "raumfahrt") {
        const [name, properties, use, origin, process, storage, risk, market] = source.split("|");
        return {
            uebersicht: name + " · Raumfahrtmaterial. Einsatz im Spiel: " + use + ".",
            eigenschaften: properties + ". Messwerte im Spiel sind offen.",
            vorkommen: "Spielvorschlag: " + origin + ". Konkrete Standorte sind offen.",
            gewinnung: "Spielvorschlag: " + process + ".",
            nutzung: use + ". Rezepte und Qualitätsstufen sind offen.",
            lagerung: "Spielvorschlag: " + storage + ".",
            gefahren: "Spielhinweis: " + risk + ".",
            handel: "Mögliche Bezugsorte im Spiel: " + market + ". Preise und Verfügbarkeit sind offen.",
        };
    }

    const [name, symbol, origin, use = "Elementforschung"] = source.split("|");
    const gas = ["O", "N", "Ne", "F", "Ar", "Cl", "Kr", "Xe", "Rn"].includes(symbol);
    const radioactive = ["Tc", "Pm", "Po", "At", "Rn", "Fr", "Ra", "Ac", "Th", "Pa", "U", "Np", "Pu", "Am", "Cm", "Bk", "Cf", "Es", "Fm"].includes(symbol) || !origin;
    const toxic = ["Be", "F", "Cl", "Br", "As", "Cd", "Hg", "Tl", "Pb", "Sb"].includes(symbol);
    const reactive = ["Li", "Na", "K", "Rb", "Cs", "Ca", "Sr", "Ba"].includes(symbol);
    const supply = origin ?? "Spezialisierte Forschungseinrichtungen";
    const research = radioactive || /anlagen|forschung/i.test(supply);
    const byproduct = /Nebenprodukte|Beiprodukte/.test(supply);
    const process = research ? "Im Spiel als kontrollierte Archivprobe beziehen."
        : gas ? "Im Spiel über ein Gasaufbereitungsmodul beziehen."
        : byproduct ? "Im Spiel bei der Raffination des Ausgangsmaterials als Nebenprodukt gewinnen."
        : "Im Spiel ein passendes Vorkommen scannen und das Material in einer Aufbereitungsanlage trennen.";
    return {
        uebersicht: name + " (" + symbol + ") · Chemisches Element. Hauptanwendung: " + use + ".",
        eigenschaften: !origin ? "Sehr schweres radioaktives Element. Als kurzlebige Forschungsprobe erfasst."
            : radioactive ? "Radioaktives Element. Eigenschaften und Nutzbarkeit hängen vom Isotop ab."
            : gas ? "Bei üblichen Umgebungsbedingungen gasförmig. Die nutzbare Form hängt von Druck und Temperatur ab."
            : symbol === "Hg" || symbol === "Br" ? "Bei üblichen Umgebungsbedingungen flüssig. Die nutzbare Form hängt von Reinheit und Temperatur ab."
            : reactive ? "Reaktives Metall. Rohmineral und reines Metall verhalten sich unterschiedlich."
            : "Bei üblichen Umgebungsbedingungen fest. Für " + use.toLocaleLowerCase("de") + " ist die Materialform entscheidend.",
        vorkommen: supply + ". Bestätigte Fundorte in Aporia sind offen.",
        gewinnung: process,
        nutzung: use + ". Freigeschaltete Rezepte in Aporia sind offen.",
        lagerung: "Spielvorschlag: " + (research ? "Versiegelte Forschungskapsel mit Freigabe."
            : gas ? "Passender Gasbehälter." : toxic || reactive ? "Geschlossene Schutzkartusche." : "Beschriftete Frachtbox, Rohmaterial und raffinierte Ware getrennt."),
        gefahren: "Spielhinweis: " + (radioactive ? "Strahlungswarnung. Beschädigte Probenkapseln im Spiel nicht aufnehmen."
            : toxic ? "Gefahrstoffwarnung beim Öffnen oder Bearbeiten."
            : reactive ? "Reaktionsgefahr bei Kontakt mit Feuchtigkeit."
            : gas ? symbol === "O" ? "Behälterdruck und Brandgefahr beachten." : "Behälterdruck prüfen. Austretendes Gas kann die Atemluft verändern."
            : "Risiken hängen von Materialform und Verarbeitung ab. Spielwerte sind offen."),
        handel: "Spielvorschlag: " + (research ? "Bezug über Forschungsstationen." : byproduct ? "Bezug über Raffinerien." : gas ? "Bezug über Gasdepots." : "Bezug über Rohstoffhändler oder Werkstätten.") + " Preise und Verfügbarkeit sind offen.",
    };
}

